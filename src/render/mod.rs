use std::collections::BTreeMap;
use std::fs;

use anyhow::{Context, Result, ensure};

use crate::domain::{ImageCatalog, ImageFamily, ImageTarget};
use crate::file_batch::replace_files;

mod common;
mod debian;
mod java;
mod scratch;

pub(super) const GENERATED_HEADER: &str = "# ------------------------------------------------------------------------------\n# NOTE: THIS FILE IS GENERATED BY `keeline render`.\n# SOURCE OF TRUTH: image.toml\n# ------------------------------------------------------------------------------\n\n";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SyncStatus {
    Generated,
    Updated,
    Unchanged,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct SyncSummary {
    pub generated: usize,
    pub updated: usize,
    pub unchanged: usize,
}

pub fn render(target: &ImageTarget) -> Result<String> {
    match target.family {
        ImageFamily::Debian => debian::render(target),
        ImageFamily::Java => java::render(target),
        ImageFamily::Scratch => scratch::render(target),
    }
}

pub fn sync_target(target: &ImageTarget) -> Result<SyncStatus> {
    let (status, replacement) = prepare_target(target)?;
    if let Some((path, contents)) = replacement {
        replace_files(BTreeMap::from([(path, contents)]))?;
    }

    Ok(status)
}

pub fn sync_catalog(catalog: &ImageCatalog) -> Result<SyncSummary> {
    sync_targets(&catalog.targets)
}

pub fn sync_targets<'a>(targets: impl IntoIterator<Item = &'a ImageTarget>) -> Result<SyncSummary> {
    let mut summary = SyncSummary::default();
    let mut replacements = BTreeMap::new();

    for target in targets {
        let (status, replacement) = prepare_target(target)?;
        match status {
            SyncStatus::Generated => summary.generated += 1,
            SyncStatus::Updated => summary.updated += 1,
            SyncStatus::Unchanged => summary.unchanged += 1,
        }
        if let Some((path, contents)) = replacement {
            ensure!(
                replacements.insert(path.clone(), contents).is_none(),
                "multiple image targets render to {}",
                path.display()
            );
        }
    }

    replace_files(replacements)?;
    Ok(summary)
}

fn prepare_target(
    target: &ImageTarget,
) -> Result<(SyncStatus, Option<(std::path::PathBuf, String)>)> {
    let rendered = render(target)?;
    match fs::read_to_string(&target.dockerfile) {
        Ok(existing) if existing == rendered => Ok((SyncStatus::Unchanged, None)),
        Ok(_) => Ok((
            SyncStatus::Updated,
            Some((target.dockerfile.clone(), rendered)),
        )),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok((
            SyncStatus::Generated,
            Some((target.dockerfile.clone(), rendered)),
        )),
        Err(error) => Err(error).with_context(|| {
            format!(
                "failed to read generated dockerfile {}",
                target.dockerfile.display()
            )
        }),
    }
}

pub fn check_target(target: &ImageTarget) -> Result<()> {
    ensure!(
        target.dockerfile.exists(),
        "dockerfile is missing for `{}`: {}",
        target.id,
        target.dockerfile.display()
    );

    let rendered = render(target)?;
    let existing = fs::read_to_string(&target.dockerfile)?;
    ensure!(
        existing == rendered,
        "dockerfile is out of sync for `{}`: run `cargo run -- render {}`",
        target.id,
        target.id
    );

    Ok(())
}

pub fn check_catalog(catalog: &ImageCatalog) -> Result<()> {
    for target in &catalog.targets {
        check_target(target)?;
    }

    Ok(())
}
